-- Oracle internal persistence extension: append-only provenance and conflict journals.
-- Apply after V001 and V002 as the dedicated AEGIS schema owner.
CREATE TABLE AEGIS_EVIDENCE (
    PROJECT_ID      VARCHAR2(128 CHAR) NOT NULL,
    EVIDENCE_ID     VARCHAR2(128 CHAR) NOT NULL,
    SUBJECT_REF     VARCHAR2(512 CHAR) NOT NULL,
    ANALYSIS_RUN_ID VARCHAR2(128 CHAR),
    KIND            VARCHAR2(32 CHAR) NOT NULL,
    REVIEW_STATUS   VARCHAR2(32 CHAR) NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    EVIDENCE_JSON   CLOB NOT NULL,
    CONSTRAINT PK_AEGIS_EVIDENCE PRIMARY KEY (PROJECT_ID, EVIDENCE_ID),
    CONSTRAINT FK_AEGIS_EVIDENCE_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES AEGIS_PROJECTS (PROJECT_ID)
);

CREATE INDEX IX_AEGIS_EVIDENCE_RUN
    ON AEGIS_EVIDENCE (PROJECT_ID, ANALYSIS_RUN_ID, CREATED_AT);

CREATE TABLE AEGIS_CONFLICT_EVENTS (
    PROJECT_ID  VARCHAR2(128 CHAR) NOT NULL,
    EVENT_ID    VARCHAR2(36 CHAR) NOT NULL,
    SUBJECT_REF VARCHAR2(512 CHAR) NOT NULL,
    EVENT_TYPE  VARCHAR2(16 CHAR) NOT NULL,
    OCCURRED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    EVENT_JSON  CLOB NOT NULL,
    CONSTRAINT PK_AEGIS_CONFLICT_EVENTS PRIMARY KEY (PROJECT_ID, EVENT_ID),
    CONSTRAINT FK_AEGIS_CONFLICT_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES AEGIS_PROJECTS (PROJECT_ID),
    CONSTRAINT CK_AEGIS_CONFLICT_TYPE CHECK (EVENT_TYPE IN ('OPENED', 'RESOLVED'))
);

CREATE INDEX IX_AEGIS_CONFLICT_SUBJECT
    ON AEGIS_CONFLICT_EVENTS (PROJECT_ID, SUBJECT_REF, OCCURRED_AT);
