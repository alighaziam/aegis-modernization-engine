-- Aegis internal persistence schema. Run as the dedicated AEGIS schema owner.
-- Oracle Database 19c or newer. This script is intentionally not auto-executed by the application.

CREATE TABLE AEGIS_PROJECTS (
    PROJECT_ID       VARCHAR2(128 CHAR) NOT NULL,
    PROJECT_NAME     VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION      VARCHAR2(2000 CHAR),
    BUSINESS_DOMAIN  VARCHAR2(256 CHAR),
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AEGIS_PROJECTS PRIMARY KEY (PROJECT_ID)
);

CREATE TABLE AEGIS_ANALYSIS_RUNS (
    RUN_ID        VARCHAR2(36 CHAR) NOT NULL,
    PROJECT_ID    VARCHAR2(128 CHAR) NOT NULL,
    MODEL_VERSION VARCHAR2(32 CHAR) NOT NULL,
    ANALYZED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    MODEL_JSON    CLOB NOT NULL,
    CONSTRAINT PK_AEGIS_ANALYSIS_RUNS PRIMARY KEY (RUN_ID),
    CONSTRAINT FK_AEGIS_RUN_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES AEGIS_PROJECTS (PROJECT_ID)
);

CREATE INDEX IX_AEGIS_RUN_PROJECT_TIME
    ON AEGIS_ANALYSIS_RUNS (PROJECT_ID, ANALYZED_AT DESC);
