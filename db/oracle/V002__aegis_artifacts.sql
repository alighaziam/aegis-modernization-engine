-- Oracle internal persistence extension: immutable source artifact content.
-- Apply after V001 as the dedicated AEGIS schema owner.
CREATE TABLE AEGIS_ARTIFACTS (
    PROJECT_ID   VARCHAR2(128 CHAR) NOT NULL,
    ARTIFACT_ID  VARCHAR2(128 CHAR) NOT NULL,
    CATEGORY     VARCHAR2(64 CHAR) NOT NULL,
    FORMAT       VARCHAR2(64 CHAR) NOT NULL,
    ORIGIN       VARCHAR2(32 CHAR) NOT NULL,
    SHA256       CHAR(64 CHAR) NOT NULL,
    SIZE_BYTES   NUMBER(19) NOT NULL,
    CONTENT_BLOB BLOB NOT NULL,
    CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AEGIS_ARTIFACTS PRIMARY KEY (PROJECT_ID, ARTIFACT_ID),
    CONSTRAINT FK_AEGIS_ARTIFACT_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES AEGIS_PROJECTS (PROJECT_ID),
    CONSTRAINT CK_AEGIS_ARTIFACT_SIZE CHECK (SIZE_BYTES >= 0)
);

CREATE INDEX IX_AEGIS_ARTIFACT_SHA
    ON AEGIS_ARTIFACTS (SHA256);
